import java.io.File;
import java.util.Collections;
import java.util.List;

import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.Parameter;
import org.apache.maven.plugins.annotations.ResolutionScope;
import org.codehaus.plexus.util.DirectoryScanner;
import org.codehaus.plexus.util.Scanner;

/**
 * Weaves all main classes.
 *
 * AspectJ Compiler Plugin.
 * @author <a href="mailto:kaare.nilsen@gmail.com">Kaare Nilsen</a>
 */
@Mojo(
        name = "compile",
        defaultPhase = LifecyclePhase.COMPILE,
        requiresDependencyResolution = ResolutionScope.COMPILE,
        threadSafe = true)
public class AjcCompileMojo extends AbstractAjcCompiler {

    /**
     * The directory for compiled classes.
     *
     */
    @Parameter(readonly = true, required = true, defaultValue = "${project.build.outputDirectory}")
    private File outputDirectory;

    /**
     * The directory for the argument file, see {@link #argumentFileName}.
     * <p>
     * The default is the output directory, so the argument file ends up in your build artifact (e.g. the JAR file).
     * It contains absolute path names, which vary between build systems and make the artifact non-reproducible, see
     * <a href="https://maven.apache.org/guides/mini/guide-reproducible-builds.html">reproducible builds</a>.
     * It is recommended to set it to <code>${project.build.directory}</code> or a subdirectory of it.
     * <p>
     * Caveat: If you configure a common directory in the plugin configuration, please make sure to choose different
     * {@link #argumentFileName}s for {@code compile} vs {@code test-compile} goal execution configurations, to avoid
     * one file overwriting the other.
     *
     * @since 1.16.2
     */
    @Parameter(defaultValue = "${project.build.outputDirectory}")
    private File argumentFileDirectory;

    /**
     * The directory for sources generated by annotation processing.
     */
    @Parameter(defaultValue = "${project.build.directory}/generated-sources/aspectj-maven-plugin")
    private File generatedSourcesDirectory;

    /**
     * <p>
     * Set the java source folders to use, specifying the includes and excludes.
     * </p>
     * <p>
     * If you don't specify this parameter, all java sources of the current project fill be used.
     * If you specify this parameter as an empty tag (i.e. &lt;sources/&gt;), all source folders will be ignored.
     * Otherwise specify the source folder(s) to use.
     * </p>
     *
     * @since 1.4
     * @see DirectoryScanner
     */
    @Parameter
    private Scanner[] sources;

    protected File getOutputDirectory() {
        return outputDirectory;
    }

    @Override
    protected File getArgumentFileDirectory() {
        return argumentFileDirectory != null ? argumentFileDirectory : outputDirectory;
    }

    @Override
    protected File getGeneratedSourcesDirectory() {
        return generatedSourcesDirectory;
    }

    /**
     * @return All directories matching {@code project.getBuild().getOutputDirectory()}.
     */
    protected List<String> getClasspathDirectories() {
        return Collections.singletonList(project.getBuild().getOutputDirectory());
    }

    /**
     * @return All directories matching {@code project.getCompileSourceRoots()}.
     */
    @SuppressWarnings("unchecked")
    protected List<String> getSourceDirectories() {
        return project.getCompileSourceRoots();
    }

    protected Scanner[] getJavaSources() {
        return sources;
    }

    protected String getAdditionalAspectPaths() {
        return null;
    }
}
